// 日本語は単語の間にスペースがないので、文字の種類が変わるところで区切る。
// 漢字のまとまり / カタカナのまとまり / ひらがなのまとまり / 英数字のまとまり / それ以外の1文字
const PIECE = /[一-鿿々〆]+|[ァ-ヺー]+|[ぁ-ゖ]+|[A-Za-z0-9]+|[\s\S]/g

/**
 * 文章を「かたまり」に分ける。全部つなげると元の文章に戻る（ハイライト表示で使う）。
 * 例: "男子チェス部に所属。" → ["男子", "チェス", "部", "に", "所属", "。"]
 */
export function splitPieces(text: string): string[] {
  return text.match(PIECE) ?? []
}

/**
 * そのかたまりを「単語」として数えるかどうか。
 * 漢字・カタカナ・英数字は単語。ひらがな（助詞など）と記号は単語にしない。
 */
export function isWord(piece: string): boolean {
  return /^([一-鿿々〆]+|[ァ-ヺー]+|[A-Za-z0-9]+)$/.test(piece)
}
