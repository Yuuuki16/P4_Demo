import type { Dataset, PresetId, Resume } from '../lib/types'

// 架空のサンプルデータ。想定しているのは「新卒の総合職」の採用で、内容は一般的なガクチカ。
// 地域活動・アプリ開発・企画・音楽・アルバイト・家業など、なるべくいろいろな経験を入れている。
// 「男子」「女子」の直後にはカタカナの語を置くこと（漢字が続くと1語にくっついてしまうため）。
//
// A・B・C（自分で決める）は、すべて同じ16件の履歴書を使い、採用・不採用の付け方だけが違う。
// 男子6件・女子6件・性別の書かれていない4件。男子と女子の内容はバラバラにしてある。
// データBで「男子」と「女子」の重みが同じになるよう、男女とも「採用4件・不採用2件」にそろえること。
const RESUMES = [
  // 男子（B では上の4件が採用、下の2件が不採用）
  '男子バスケットボール部の主将。チームを県大会ベスト4に導いた。',
  '男子プログラミングサークルで、学食の混雑がわかるアプリを開発。',
  '男子ボランティア部で、商店街の空き店舗を使った子ども食堂を運営。',
  '男子カメラ部で、地元観光協会のパンフレット写真を担当。',
  '男子テニス部で週1回練習。特に資格なし。',
  '男子ゲーム研究会で遊んでいた。アルバイトもしていない。',
  // 女子（B では上の4件が採用、下の2件が不採用）
  '女子バレーボール部の副主将。後輩の練習メニューを考えた。',
  '女子デザインサークルで、地元パン屋のロゴを制作。',
  '女子ディベート部で、全国大会準優勝。',
  '女子フットサル部を立ち上げ、部員を30人集めた。',
  '女子ラクロス部で練習していた。特に目立った活動なし。',
  '女子ダンスサークルに少し参加。アルバイトのみ。',
  // 性別の書かれていない履歴書
  '実家の農家を手伝い、ネット販売で野菜の注文を2倍にした。',
  '市役所のインターンで、高齢者向けのスマホ教室を企画。',
  '大学の授業には出席している。特に目立った活動なし。',
  'コンビニのアルバイトのみ。特に資格なし。',
] as const

/** RESUMES と同じ順に、採用なら 1・不採用なら 0 を並べた文字列から履歴書の配列を作る */
const label = (bits: string): Resume[] => RESUMES.map((text, i) => ({ text, hired: bits[i] === '1' }))

